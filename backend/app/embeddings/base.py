"""Abstract base class and contract for embedding providers."""

from abc import ABC, abstractmethod
import math
from typing import List


class EmbeddingProviderError(Exception):
    """Base exception for all embedding generation errors."""
    pass


class BaseEmbeddingProvider(ABC):
    """Abstract interface defining the contract for all dense embedding providers."""

    @property
    @abstractmethod
    def provider_name(self) -> str:
        """Name of the embedding provider (e.g., 'local', 'gemini')."""
        pass

    @property
    @abstractmethod
    def model_name(self) -> str:
        """Name of the specific model (e.g., 'sentence-transformers/all-MiniLM-L6-v2')."""
        pass

    @property
    @abstractmethod
    def dimension(self) -> int:
        """Dimensionality of the dense vector generated by this provider."""
        pass

    @abstractmethod
    def embed_text(self, text: str) -> List[float]:
        """Generates a dense vector embedding for a single text string."""
        pass

    @abstractmethod
    def embed_texts(self, texts: List[str]) -> List[List[float]]:
        """Generates dense vector embeddings for a list of text strings in matching order."""
        pass

    def validate_vector(self, vector: List[float]) -> bool:
        """Validates that an embedding vector conforms to dimension, numeric, and finite constraints."""
        if not vector or not isinstance(vector, list):
            raise EmbeddingProviderError("Generated embedding vector cannot be empty or non-list.")
        if len(vector) != self.dimension:
            raise EmbeddingProviderError(
                f"Embedding dimension mismatch: expected {self.dimension}, got {len(vector)}"
            )
        for idx, val in enumerate(vector):
            if not isinstance(val, (int, float)) or math.isnan(val) or math.isinf(val):
                raise EmbeddingProviderError(
                    f"Invalid non-numeric or non-finite value at index {idx}: {val}"
                )
        return True

    def validate_vectors(self, vectors: List[List[float]], expected_count: int) -> bool:
        """Validates a batch of embedding vectors against count and individual constraints."""
        if len(vectors) != expected_count:
            raise EmbeddingProviderError(
                f"Batch vector count mismatch: expected {expected_count}, got {len(vectors)}"
            )
        for vec in vectors:
            self.validate_vector(vec)
        return True
